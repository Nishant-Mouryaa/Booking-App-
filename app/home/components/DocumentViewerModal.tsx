"use client";

import { useEffect, useRef } from "react";

interface DocContent {
  [key: string]: any;
}

interface Document {
  id: number;
  name: string;
  date: string;
  type: string;
  pages: number;
  content: DocContent;
}

interface Props {
  doc: Document;
  patientName: string;
  onClose: () => void;
}

const fmtDate = (iso: string) =>
  new Date(iso).toLocaleDateString("en-IN", {
    day: "numeric", month: "long", year: "numeric",
  });

const TYPE_COLORS: Record<string, string> = {
  Discharge:   "#3b82f6",
  Insurance:   "#10b981",
  Vaccination: "#8b5cf6",
};

// ── Build downloadable text per document type ─────────────────────────────────
function buildTextContent(doc: Document, patientName: string): string {
  const sep = "=".repeat(60);
  const sub = "-".repeat(60);
  const c   = doc.content;

  const header = [
    sep,
    "          SHEDULA HEALTH — PATIENT DOCUMENT",
    sep,
    `Document : ${doc.name}`,
    `Patient  : ${patientName}`,
    `Date     : ${fmtDate(doc.date)}`,
    `Type     : ${doc.type}`,
    "",
  ];

  let body: string[] = [];

  if (doc.type === "Discharge") {
    body = [
      sub, "DISCHARGE SUMMARY", sub,
      `Hospital         : ${c.hospital}`,
      `Date of Admission: ${fmtDate(c.admissionDate)}`,
      `Date of Discharge: ${fmtDate(c.dischargeDate)}`,
      `Diagnosis        : ${c.diagnosis}`,
      "",
      "Treatment:",
      c.treatment,
      "",
      sub, "MEDICATIONS AT DISCHARGE", sub,
      ...(c.medications as any[]).map(
        (m: any) => `  • ${m.name} — ${m.instruction}`
      ),
      "",
      `Follow-up: ${c.followUp}`,
    ];
  } else if (doc.type === "Insurance") {
    body = [
      sub, "INSURANCE DETAILS", sub,
      `Provider         : ${c.provider}`,
      `Policy Number    : ${c.policyNo}`,
      `Insured Name     : ${c.insuredName}`,
      `Sum Insured      : ${c.sumInsured}`,
      `Valid From       : ${c.validFrom}`,
      `Valid To         : ${c.validTo}`,
      `TPA              : ${c.tpaName}`,
      `Emergency No     : ${c.emergencyNo}`,
      `Network Hospitals: ${c.networkHospitals}`,
    ];
  } else if (doc.type === "Vaccination") {
    body = [
      sub, "VACCINATION CERTIFICATE", sub,
      `Vaccine          : ${c.vaccine}`,
      `Beneficiary      : ${c.beneficiaryName}`,
      `Date of Birth    : ${c.dob}`,
      "",
      `Dose 1 Date      : ${fmtDate(c.dose1Date)}`,
      `Dose 1 Batch     : ${c.dose1Batch}`,
      `Dose 1 Site      : ${c.dose1Site}`,
      "",
      `Dose 2 Date      : ${fmtDate(c.dose2Date)}`,
      `Dose 2 Batch     : ${c.dose2Batch}`,
      `Dose 2 Site      : ${c.dose2Site}`,
      "",
      `Booster Date     : ${fmtDate(c.boosterDate)}`,
      `Booster Batch    : ${c.boosterBatch}`,
      `Booster Site     : ${c.boosterSite}`,
      "",
      `Certificate No   : ${c.certificateNo}`,
    ];
  }

  return [
    ...header,
    ...body,
    "",
    sep,
    "* Sample document generated by Shedula Health Demo *",
    sep,
  ].join("\n");
}

function downloadDoc(doc: Document, patientName: string) {
  const text = buildTextContent(doc, patientName);
  const blob = new Blob([text], { type: "text/plain" });
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement("a");
  a.href     = url;
  a.download = `${doc.name.replace(/[^a-zA-Z0-9]/g, "_")}.txt`;
  a.click();
  URL.revokeObjectURL(url);
}

