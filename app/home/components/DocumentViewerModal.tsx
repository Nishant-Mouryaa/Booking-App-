// ── Main Modal ────────────────────────────────────────────────────────────────
export default function DocumentViewerModal({ doc, patientName, onClose }: Props) {
  const backdropRef = useRef<HTMLDivElement>(null);
  const color = TYPE_COLORS[doc.type] ?? "#6366f1";

  useEffect(() => {
    const handler = (e: KeyboardEvent) => { if (e.key === "Escape") onClose(); };
    document.addEventListener("keydown", handler);
    return () => document.removeEventListener("keydown", handler);
  }, [onClose]);

  useEffect(() => {
    document.body.style.overflow = "hidden";
    return () => { document.body.style.overflow = ""; };
  }, []);

  return (
    <div
      className="rvm-backdrop"
      ref={backdropRef}
      onClick={(e) => { if (e.target === backdropRef.current) onClose(); }}
    >
      <div className="rvm-modal" role="dialog" aria-label={doc.name}>

        {/* ── Header ── */}
        <div className="rvm-header">
          <div className="rvm-header__left">
            <div className="rvm-header__icon"
              style={{ background: `${color}18`, color }}>
              <svg width="22" height="22" viewBox="0 0 24 24" fill="none">
                <path d="M14 2H6a2 2 0 00-2 2v16a2 2 0 002 2h12a2 2 0 002-2V8l-6-6z"
                  stroke="currentColor" strokeWidth="1.8"
                  strokeLinecap="round" strokeLinejoin="round" />
                <path d="M14 2v6h6" stroke="currentColor"
                  strokeWidth="1.8" strokeLinecap="round" />
              </svg>
            </div>
            <div>
              <h2 className="rvm-header__title">{doc.name}</h2>
              <p className="rvm-header__sub">
                {doc.type} · {fmtDate(doc.date)} · {doc.pages} page{doc.pages > 1 ? "s" : ""}
              </p>
            </div>
          </div>
          <div className="rvm-header__right">
            <span className="rvm-status"
              style={{ background: `${color}15`, color, borderColor: `${color}40` }}>
              {doc.type}
            </span>
            <button
              className="rvm-btn rvm-btn--outline"
              onClick={() => downloadDoc(doc, patientName)}
            >
              <svg width="14" height="14" viewBox="0 0 24 24" fill="none">
                <path d="M21 15v4a2 2 0 01-2 2H5a2 2 0 01-2-2v-4M7 10l5 5 5-5M12 15V3"
                  stroke="currentColor" strokeWidth="2"
                  strokeLinecap="round" strokeLinejoin="round" />
              </svg>
              Download
            </button>
            <button className="rvm-close" onClick={onClose}>
              <svg width="18" height="18" viewBox="0 0 24 24" fill="none">
                <path d="M18 6L6 18M6 6l12 12" stroke="currentColor"
                  strokeWidth="2.5" strokeLinecap="round" />
              </svg>
            </button>
          </div>
        </div>

        {/* ── Content ── */}
        <div className="rvm-scroll">
          {doc.type === "Discharge"   && <DischargeContent   c={doc.content} />}
          {doc.type === "Insurance"   && <InsuranceContent   c={doc.content} patientName={patientName} />}
          {doc.type === "Vaccination" && <VaccinationContent c={doc.content} />}

          <p className="rvm-disclaimer">
            * Sample document for demonstration purposes. Not a real medical record.
          </p>
        </div>
      </div>
    </div>
  );
}